/**
 * 営業日の定義。
 *
 * **「1日」は Asia/Tokyo のカレンダー日付 (00:00 以上 翌 00:00 未満) とする。**
 *
 * 根拠: パン屋の営業時間は朝の開店から夕方の閉店までで日を跨がない。
 * 深夜営業の飲食店のように「営業日は 5:00 始まり」という補正を入れる理由がなく、
 * 入れるとかえってレシートの日付と集計がずれる。単純な暦日でよい。
 *
 * タイムゾーンを固定するのは、サーバやコンテナの TZ 設定で売上の集計単位が
 * 変わらないようにするため。店舗は日本にあるので JST 固定でよい。
 * (複数タイムゾーンに店舗を持つようになったら、店舗ごとの営業日定義が要る)
 */
const JST_OFFSET_MS = 9 * 60 * 60 * 1000;

/** 販売時刻 (絶対時刻) を営業日 (YYYY-MM-DD) に落とす。 */
export function businessDateOf(soldAt: Date): string {
  // JST の壁時計時刻に直してから日付部分だけ取る。
  const jst = new Date(soldAt.getTime() + JST_OFFSET_MS);
  return jst.toISOString().slice(0, 10);
}
